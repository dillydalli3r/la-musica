#!/usr/bin/env python
"""Reading a cleared session out of a browser (`server/browsercookies.py`).

Everything here is offline and deterministic: the yt-dlp the module drives is
stubbed at the `subprocess.run` seam (a real yt-dlp would read the machine's
own profile, which no test can depend on), and the browser profiles are
fabricated in a temp folder. What is proved is the plumbing the app controls:

  * a jar is only used when yt-dlp actually WROTE cookies — a run that wrote
    nothing, or nothing but its header comment, is "could not read that
    browser", never an empty credential stored over a working one;
  * the path handed to `--cookies` does NOT exist when yt-dlp starts (it is
    READ first: an empty file is "not a Netscape cookies file" and yt-dlp
    aborts before extracting anything — MEASURED, that was a real bug here);
  * the User-Agent comes from the profile, because MEASURED 2026-10-10 the
    same jar answers 200 with Firefox's UA and 403 with the app's built-in
    Chrome one.

Why the module exists at all, and what it is for, is in its own docstring.
"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from server import browsercookies as bc  # noqa: E402

PASS = 0
FAIL = 0


def ok(cond, label):
    global PASS, FAIL
    if cond:
        PASS += 1
    else:
        FAIL += 1
        print(f"FAILED: {label}")


JAR_OK = ("# Netscape HTTP Cookie File\n"
          "# This file is generated by yt-dlp.  Do not edit.\n\n"
          ".rateyourmusic.com\tTRUE\t/\tTRUE\t1823199182\tcf_clearance\tTOKEN\n"
          "rateyourmusic.com\tFALSE\t/\tFALSE\t1826211867\tis_logged_in\t1\n")


class _Result:
    def __init__(self, rc=0):
        self.returncode = rc
        self.stdout = b""
        self.stderr = b""


def stub_run(writes):
    """Replace the module's subprocess seam.
…
    `writes` is a callable given the path yt-dlp was handed; it writes whatever
    that browser profile "held". Returns a list of the paths, so a test can
    check the file did not exist when the process started.
    """
    seen = []

    def fake(cmd, capture_output=None, timeout=None, **kw):
        path = cmd[cmd.index("--cookies") + 1]
        seen.append(os.path.exists(path))
        writes(path)
        return _Result()

    bc.subprocess.run = fake
    return seen


class _FakeJar(list):
    """A `yt_dlp.cookies.YoutubeDLCookieJar` stand-in: `save` writes the jar."""

    def __init__(self, rows, text=JAR_OK):
        super().__init__(rows)
        self.text = text
        self.saved = []

    def save(self, path, ignore_discard=False, ignore_expires=False):
        self.saved.append((ignore_discard, ignore_expires))
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(self.text)


def stub_module(rows=1, text=JAR_OK, raises=False):
    """Point the module route at a fake `yt_dlp.cookies`.

    The route exists because the app's OWN yt-dlp install is a pip folder with
    no spawnable binary — so a suite must be able to prove it without a real
    browser, a real profile, or the machine's own cookies.
    """
    import types
    jar = _FakeJar(range(rows), text)

    def extract(browser, logger=None):
        if raises:
            raise RuntimeError("Failed to decrypt with DPAPI")
        return jar

    fake = types.SimpleNamespace(
        cookies=types.SimpleNamespace(extract_cookies_from_browser=extract),
        __name__="yt_dlp", __version__="test")
    bc._module_state = {"module": fake, "tried": True}
    return jar


_real_run = bc.subprocess.run
_real_ytdlp = bc._ytdlp
_real_module_state = dict(bc._module_state)
_real_ff = bc.firefox_profiles
_real_cr = bc.chromium_profiles
tmp = tempfile.mkdtemp(prefix="bc-test-")

try:
    # ----------------------------------------------------------------------- #
    # What the machine has, and the shape the panel reads
    # ----------------------------------------------------------------------- #
    ok(isinstance(bc.installed(), dict), "installed() is a mapping of browser -> profiles")
    ok(isinstance(bc.available(), list), "available() is a list of rows")
    ok(all(len(row) == 3 for row in bc.available()),
       "…each row is (id, label, profile count)")
    ok(bc.ttl_seconds() > 0, "a jar has a freshness window")

    # ----------------------------------------------------------------------- #
    # The module route — the one the app's own install needs
    # ----------------------------------------------------------------------- #
    # MEASURED 2026-10-11: `<music>/.mlo/tools/yt-dlp v2026.8.19` holds
    # `bin/yt-dlp` with no `.exe`, so the tool scan answers `ytdlp_exe: None`
    # and an exe-only reader returned "" for every browser — an empty borrowed
    # session, and RYM refused the release page. The module route needs no exe.
    bc._module_state = {"module": None, "tried": True}      # no module yet
    bc._ytdlp = lambda: ""
    ok(bc.jar("firefox") == "",
       "no module and no yt-dlp executable -> '', never a crash")

    jar = stub_module()
    bc._ytdlp = lambda: r"C:\nope\yt-dlp.exe"                # exe is still absent
    got = bc.jar("firefox")
    ok("is_logged_in" in got and "cf_clearance" in got,
       f"with NO executable at all, the module reads the jar: {got[:40]!r}")
    ok(jar.saved and jar.saved[0] == (True, True),
       f"…keeping session cookies (ignore_discard): {jar.saved}")

    stub_module(rows=0)
    ok(bc.jar("firefox") == "",
       "a profile that holds no cookies -> '' (never a credential)")

    stub_module(text="# Netscape HTTP Cookie File\n# generated by yt-dlp\n")
    ok(bc.jar("firefox") == "",
       "a module jar with only its header is 'nothing was read'")

    # A profile the module cannot read (Chrome's DPAPI refusal, a locked
    # store) must fall through to the executable rather than fail the read.
    stub_module(raises=True)
    stub_run(lambda path: open(path, "w", encoding="utf-8").write(JAR_OK))
    got = bc.jar("firefox")
    ok("is_logged_in" in got, f"a module refusal falls back to the exe: {got[:40]!r}")

    # ----------------------------------------------------------------------- #
    # Reading the jar through the executable
    # ----------------------------------------------------------------------- #
    bc._module_state = {"module": None, "tried": True}
    bc._ytdlp = lambda: ""
    ok(bc.jar("firefox") == "", "no yt-dlp installed -> '' , never a crash")
    bc._ytdlp = lambda: r"C:\nope\yt-dlp.exe"

    ok(bc.jar("not-a-browser") == "",
       "a browser yt-dlp does not know -> '' (never a spawn)")

    seen = stub_run(lambda path: open(path, "w", encoding="utf-8").write(JAR_OK))
    got = bc.jar("firefox")
    ok("cf_clearance" in got and "is_logged_in" in got,
       f"a jar yt-dlp wrote is returned: {got[:40]!r}")
    ok(seen and seen[0] is False,
       "…and the --cookies path did NOT exist when yt-dlp started")

    stub_run(lambda path: open(path, "w", encoding="utf-8").write(
        "# Netscape HTTP Cookie File\n# This file is generated by yt-dlp."
        "  Do not edit.\n\n"))
    ok(bc.jar("firefox") == "",
       "a jar with only its header is 'nothing was read', not a credential")

    stub_run(lambda path: None)           # wrote no file at all
    ok(bc.jar("firefox") == "",
       "yt-dlp that wrote nothing -> '' (the old credential stands)")

    # ----------------------------------------------------------------------- #
    # The User-Agent half of the credential
    # ----------------------------------------------------------------------- #
    prof = os.path.join(tmp, "ffprof")
    os.makedirs(prof, exist_ok=True)
    with open(os.path.join(prof, "compatibility.ini"), "w", encoding="utf-8") as fh:
        fh.write("[Compatibility]\nLastVersion=157.0.1\n")
    bc.firefox_profiles = lambda: [prof]
    ua = bc.user_agent("firefox")
    ok(ua == ("Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:157.0.1) "
              "Gecko/20100101 Firefox/157.0.1"),
       f"the Firefox UA is built from the profile's own version: {ua!r}")

    cprof = os.path.join(tmp, "chrome-user-data", "Default")
    os.makedirs(cprof, exist_ok=True)
    with open(os.path.join(cprof, "Last Version"), "w", encoding="utf-8") as fh:
        fh.write("154.0.8037.99\n")
    bc.chromium_profiles = lambda b: [cprof] if b == "chrome" else []
    cua = bc.user_agent("chrome")
    ok("Chrome/154.0.8037.99" in cua and "Windows NT 10.0" in cua,
       f"the Chrome UA is built from the profile's own version: {cua!r}")

    bc.firefox_profiles = lambda: []
    ok(bc.user_agent("firefox") == "",
       "no profile -> no UA, so a stale one is never stored beside a fresh jar")

    # A browser the module does not know has no UA either.
    ok(bc.user_agent("not-a-browser") == "", "an unknown browser has no UA")
finally:
    bc.subprocess.run = _real_run
    bc._ytdlp = _real_ytdlp
    bc._module_state = _real_module_state
    bc.firefox_profiles = _real_ff
    bc.chromium_profiles = _real_cr
    try:
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)
    except OSError:
        pass

print(f"browsercookies: {PASS} passed, {FAIL} failed")
raise SystemExit(1 if FAIL else 0)